#!/usr/bin/env python3
"""Writes tests/unit/fixtures.inc: the .tar.gz files the update tests read, as C++ byte arrays.

Run it again only to change the fixtures (python3 -I tests/unit/make_fixtures.py); the output is committed so the
tests need neither Python nor tar. Two archives come from GNU tar itself (the format a release's tar.gz uses), the
hostile ones from Python's tarfile, which writes any name it is given.
"""
import gzip
import io
import os
import subprocess
import sys
import tarfile
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
LONG = "resources/" + "deep/" * 22 + "file.txt"  # past ustar's 100 + 155 limits: a GNU 'L' or pax 'x' record


def gnu_tar(fmt):
    with tempfile.TemporaryDirectory() as tmp:
        top = os.path.join(tmp, "God Hand Rearmed")
        os.makedirs(os.path.join(top, os.path.dirname(LONG)))
        os.makedirs(os.path.join(top, "memcards", "mc0"))
        files = {
            "GHR": b"\x7fELF fake program\n",
            "GHR.ini": b"[Video]\nAspectRatio=16:9\n",
            "resources/readme.txt": b"hello from the resources\n",
            "memcards/mc0/save.bin": b"must never be written by an update\n",
            LONG: b"long name\n",
        }
        for name, data in files.items():
            with open(os.path.join(top, name), "wb") as f:
                f.write(data)
        os.chmod(os.path.join(top, "GHR"), 0o755)
        os.chmod(os.path.join(top, "GHR.ini"), 0o644)
        os.symlink("GHR", os.path.join(top, "libfake.so.0"))
        out = os.path.join(tmp, "out.tar.gz")
        subprocess.run(["tar", "--format=" + fmt, "--owner=0", "--group=0", "--numeric-owner", "--sort=name",
                        "--mtime=@0", "-czf", out, "-C", tmp, "God Hand Rearmed"], check=True)
        with open(out, "rb") as f:
            return f.read()


def py_tar(names):
    raw = io.BytesIO()
    with tarfile.open(fileobj=raw, mode="w", format=tarfile.GNU_FORMAT) as tar:
        for name in names:
            info = tarfile.TarInfo(name)
            data = b"x\n"
            info.size = len(data)
            info.mode = 0o644
            tar.addfile(info, io.BytesIO(data))
    return gzip.compress(raw.getvalue(), mtime=0)


def array(name, data):
    lines = ["static const unsigned char %s[] = {" % name]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    fixtures = [
        ("kGnuTarGz", gnu_tar("gnu")),
        ("kPaxTarGz", gnu_tar("pax")),
        ("kDotDotTarGz", py_tar(["God Hand Rearmed/GHR", "God Hand Rearmed/../../evil.txt"])),
        ("kAbsoluteTarGz", py_tar(["/tmp/evil.txt"])),
    ]
    out = ["// Generated by tests/unit/make_fixtures.py; do not edit.", "// Long name in the good archives: " + LONG, ""]
    out += [array(n, d) for n, d in fixtures]
    with open(os.path.join(HERE, "fixtures.inc"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.join(HERE, "fixtures.inc"), [(n, len(d)) for n, d in fixtures])


if __name__ == "__main__":
    sys.exit(main())
